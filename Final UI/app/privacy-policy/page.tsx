// A simple parser to convert basic Markdown to JSX elements
// This is very rudimentary and only handles headings, paragraphs, bold, and lists.
// For more complex Markdown, a library like react-markdown is recommended.
const SimpleMarkdownRenderer = ({ markdown }: { markdown: string }) => {
  const lines = markdown.trim().split('\\n');
  const elements = [];
  let currentList: React.JSX.Element[] = [];

  const flushList = () => {
    if (currentList.length > 0) {
      elements.push(<ul key={`ul-${elements.length}`} className="list-disc list-inside my-4 pl-4 space-y-2 text-brand-text-medium">{currentList}</ul>);
      currentList = [];
    }
  };

  for (let i = 0; i < lines.length; i++) {
    let line = lines[i].trim();

    // Handle headings
    if (line.startsWith('## ')) {
      flushList();
      // Use font-heading for H2, consistent with landing page sections
      elements.push(<h2 key={i} style={{ color: 'blue', fontFamily: 'Impact, sans-serif' }} className="font-heading text-2xl lg:text-3xl text-brand-text-dark mt-10 mb-4">{line.substring(3)}</h2>);
      continue;
    }
    if (line.startsWith('# ')) {
      flushList();
      // Use font-logo for H1, consistent with landing page main title
      elements.push(<h1 key={i} style={{ color: 'red', fontFamily: 'Arial, sans-serif' }} className="font-logo text-3xl lg:text-4xl text-brand-text-darker mt-8 mb-6">{line.substring(2)}</h1>);
      continue;
    }

    // Handle list items (simple unordered lists)
    if (line.startsWith('*   ') || line.startsWith('-   ')) {
      const listItemText = line.substring(4);
      // Process bold within list item
      const parts = listItemText.split(/(\*\*.*?\*\*)/g).map((part, index) => {
        if (part.startsWith('**') && part.endsWith('**')) {
          return <strong key={index} className="font-semibold text-brand-text-dark">{part.substring(2, part.length - 2)}</strong>;
        }
        return part;
      });
      currentList.push(<li key={`${i}-${currentList.length}`}>{parts}</li>);
      continue;
    } else {
      flushList(); // If it's not a list item, and there was a list, flush it
    }

    // Handle paragraphs and bold text
    if (line) {
      const parts = line.split(/(\*\*.*?\*\*)/g).map((part, index) => {
        if (part.startsWith('**') && part.endsWith('**')) {
          return <strong key={index} className="font-semibold text-brand-text-dark">{part.substring(2, part.length - 2)}</strong>;
        }
        return part;
      });
      // Use text-base for paragraphs, consistent with landing page feature descriptions
      elements.push(<p key={i} className="text-base text-brand-text-medium leading-relaxed my-4">{parts}</p>);
    } else {
      // Preserve empty lines as paragraph breaks if needed, by not rendering anything or a specific spacer
      // elements.push(<div key={`br-${i}`} className="h-4" />); // Example of a spacer
    }
  }
  flushList(); // Flush any remaining list items

  return <>{elements}</>;
};


